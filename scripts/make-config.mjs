#!/usr/bin/env node
/* Write firebase-config.js from .env (on your computer) or from environment
   variables (GitHub Actions reads them from the repository's secrets).
   The file is git-ignored; without values it switches shared saving off and
   every room keeps its work in the visitor's own browser.

       node scripts/make-config.mjs
*/
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const env = { ...process.env };
const dotenv = join(root, ".env");
if (existsSync(dotenv)) {
  for (const line of readFileSync(dotenv, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith("#") && !env[m[1]]) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}
const keys = { apiKey:"FIREBASE_API_KEY", authDomain:"FIREBASE_AUTH_DOMAIN", projectId:"FIREBASE_PROJECT_ID",
               storageBucket:"FIREBASE_STORAGE_BUCKET", messagingSenderId:"FIREBASE_MESSAGING_SENDER_ID", appId:"FIREBASE_APP_ID" };
const cfg = {};
for (const [k, v] of Object.entries(keys)) if (env[v]) cfg[k] = env[v];

const ok = cfg.apiKey && cfg.projectId;
writeFileSync(join(root, "firebase-config.js"),
  "/* generated by scripts/make-config.mjs — do not commit */\n" +
  `window.LAM_FIREBASE = ${ok ? JSON.stringify(cfg, null, 2) : "null"};\n`);
console.log(ok ? `firebase-config.js written for project "${cfg.projectId}"`
               : "firebase-config.js written without Firebase (no FIREBASE_API_KEY / FIREBASE_PROJECT_ID): rooms will save in each browser only");
